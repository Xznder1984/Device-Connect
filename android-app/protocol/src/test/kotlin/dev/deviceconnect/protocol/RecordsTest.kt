/**
 * The wire record layer (docs/protocol.md section 2.2.1).
 *
 * The record layer turns a Noise transport into a framed stream, so it is
 * asserted against the shared golden vectors rather than trusted. Those vectors
 * are generated by the Rust implementation, which means agreement here is what
 * makes the phone and the PC able to read each other's bytes at all.
 */
class RecordsTest {

    private val vectors = TestVectors.load("noise-kat.json")

    /**
     * Replay the golden handshake with the fixed ephemerals, exactly as
     * `NoiseKatTest` does, and return both transport pairs.
     */
    private fun replayHandshake(): Pair<NoiseTransport, NoiseTransport> {
        val prologue = TestVectors.hex(vectors.get("prologueHex").asString)
        val initiatorStatic = TestVectors.hex(vectors.get("initiatorStaticPrivHex").asString)
        val responderStatic = TestVectors.hex(vectors.get("responderStaticPrivHex").asString)
        val initiatorEph = TestVectors.hex(vectors.get("initiatorEphPrivHex").asString)
        val responderEph = TestVectors.hex(vectors.get("responderEphPrivHex").asString)

        val initiator = Noise.handshake(HandshakeState.INITIATOR, prologue, initiatorStatic, initiatorEph)
        val msg1 = Noise.write(initiator, ByteArray(0))
        assertEquals(vectors.get("msg1Hex").asString, TestVectors.unhex(msg1), "msg1")
        Noise.read(initiator, TestVectors.hex(vectors.get("msg2Hex").asString))
        val msg3 = Noise.write(initiator, ByteArray(0))
        assertEquals(vectors.get("msg3Hex").asString, TestVectors.unhex(msg3), "msg3")

        val responder = Noise.handshake(HandshakeState.RESPONDER, prologue, responderStatic, responderEph)
        Noise.read(responder, msg1)
        val msg2 = Noise.write(responder, ByteArray(0))
        assertEquals(vectors.get("msg2Hex").asString, TestVectors.unhex(msg2), "msg2")
        Noise.read(responder, msg3)

        return Noise.transport(initiator) to Noise.transport(responder)
    }

    /** u32be length prefix followed by [payload], for building expected values. */
    private fun record(payload: ByteArray): ByteArray {
        val out = ByteArrayOutputStream()
        DataOutputStream(out).apply {
            writeInt(payload.size)
            write(payload)
        }
        return out.toByteArray()
    }

    /**
     * The whole point of the record layer: the bytes this implementation writes
     * must be byte-for-byte what the Rust reference implementation writes for
     * the same golden input, or the two platforms cannot talk.
     */
    @Test
    fun recordLayerMatchesTheGoldenTransports() {
        val (initiator, responder) = replayHandshake()
        val transports = vectors.getAsJsonArray("transports")

        val initiatorPlain = transports[0].asJsonObject.get("plain").asString
        val initiatorCipher = TestVectors.hex(transports[0].asJsonObject.get("cipherHex").asString)
        assertArrayEquals(
            record(initiatorCipher),
            Records.encode(initiator.encrypt(initiatorPlain.toByteArray(Charsets.US_ASCII))),
            "initiator transport record",
        )

        val responderPlain = transports[1].asJsonObject.get("plain").asString
        val responderCipher = TestVectors.hex(transports[1].asJsonObject.get("cipherHex").asString)
        assertArrayEquals(
            record(responderCipher),
            Records.encode(responder.encrypt(responderPlain.toByteArray(Charsets.US_ASCII))),
            "responder transport record",
        )
    }

    @Test
    fun decodingRecoversThePayloadAndItsLength() {
        val payload = "hello record".toByteArray()
        val encoded = Records.encode(payload)

        val result = Records.decode(encoded)
        val decoded = assertInstanceOf(Records.DecodeResult.Decoded::class.java, result)
        assertArrayEquals(payload, decoded.payload)
        assertEquals(encoded.size, decoded.bytesConsumed)
    }

    @Test
    fun partialRecordsAskForMore() {
        val encoded = Records.encode("incomplete record".toByteArray())
        // Every proper prefix is indistinguishable from "keep reading"; only the
        // full record decodes. A decoder that guessed here would desynchronize
        // the stream on any split TCP segment.
        for (cut in 0 until encoded.size) {
            val partial = encoded.copyOfRange(0, cut)
            assertTrue(Records.decode(partial) is Records.DecodeResult.NeedMore, "cut at $cut")
        }
    }

    @Test
    fun zeroLengthAndOversizedRecordsAreRejected() {
        // body_len of zero is invalid on both paths, whatever the caller's cap.
        assertThrows(ProtocolException::class.java) { Records.decode(ByteArray(8)) }

        // A well-formed length above the caller's cap is rejected up front,
        // before any allocation proportional to the claimed length.
        val tooBig = ByteArrayOutputStream().apply {
            DataOutputStream(this).apply {
                writeInt(100)
                write(ByteArray(100))
            }
        }.toByteArray()
        assertThrows(ProtocolException::class.java) { Records.decode(tooBig, max = 16) }
    }

    @Test
    fun handshakeAndTransportCapsAreIndependent() {
        // A payload just under the transport cap is legal on the transport path.
        val bigPayload = ByteArray(Records.MAX_TRANSPORT_RECORD - Records.LENGTH_BYTES)
        val record = Records.encode(bigPayload)
        assertInstanceOf(Records.DecodeResult.Decoded::class.java, Records.decode(record))

        // The same record is far above what a handshake message may be, so a
        // peer claiming a 1 MiB handshake is refused rather than obeyed.
        assertThrows(ProtocolException::class.java) {
            Records.decode(record, max = Records.MAX_HANDSHAKE_RECORD)
        }
    }

    @Test
    fun tamperedCiphertextFailsTheTagCheck() {
        val (initiator, responder) = replayHandshake()
        val ciphertext = initiator.encrypt("payload".toByteArray())

        // Flipping one bit must fail the Poly1305 tag check. The receiver
        // treats the connection as broken instead of accepting different
        // plaintext, which is what makes the record layer tamper-proof even
        // though its length prefix lives outside the AEAD.
        val tampered = ciphertext.copyOf()
        tampered[0] = (tampered[0].toInt() xor 0x01).toByte()
        assertThrows(ProtocolException::class.java) { responder.decrypt(tampered) }
    }

    @Test
    fun tamperedLengthPrefixNeverYieldsPlaintext() {
        val (initiator, responder) = replayHandshake()
        val ciphertext = initiator.encrypt("payload".toByteArray())

        // The length prefix sits outside the AEAD, so a peer that flips it
        // causes either a truncated read or a tag-check failure. Either way the
        // record is never accepted, which is the property section 2.2.1 claims.
        val tampered = Records.encode(ciphertext)
        tampered[3] = (tampered[3].toInt() + 1).toByte()
        val rejected = runCatching {
            responder.decrypt(Records.read(DataInputStream(ByteArrayInputStream(tampered))))
        }
        assertTrue(rejected.isFailure, "tampered length must not decrypt")
    }

    @Test
    fun secureTransportRoundTripsFramesOverAPipe() {
        val toResponder = PipedOutputStream()
        val fromInitiator = PipedInputStream(toResponder, PIPE_SIZE)
        val toInitiator = PipedOutputStream()
        val fromResponder = PipedInputStream(toInitiator, PIPE_SIZE)

        val initiator = SecureTransport(WireStream(fromResponder, toResponder), replayHandshake().first)
        val responder = SecureTransport(WireStream(fromInitiator, toInitiator), replayHandshake().second)

        val sent = Frame(Channel.CONTROL, MType.REQUEST, Framing.FLAG_JSON, 7, "{}".toByteArray())
        initiator.sendFrame(sent)
        assertEquals(sent, responder.readFrame(), "initiator -> responder")

        val reply = Frame(Channel.CONTROL, MType.RESPONSE, Framing.FLAG_JSON, 7, """{"ok":true}""".toByteArray())
        responder.sendFrame(reply)
        assertEquals(reply, initiator.readFrame(), "responder -> initiator")

        initiator.close()
        responder.close()
    }

